-- 유지보수 세션이 실행되는 샌드박스 환경의 아웃바운드 네트워크 정책이
-- *.pages.dev 같은 임의 사이트 접속을 막아서, 세션이 관리자 API를 직접
-- 폴링하는 방식이 동작하지 않는 문제가 발견됨(GitHub API 호출은 별도
-- 경로라 정상 동작). 그래서 에러 발생 시 서버(Cloudflare Worker, 아웃바운드
-- 제한 없음)가 직접 GitHub 이슈를 만들고, 유지보수 세션은 GitHub 이슈만
-- 확인하는 방식으로 전환 — 이 컬럼에 생성된 이슈 URL을 기록해 어드민 UI에서도
-- 바로 링크를 볼 수 있게 한다.
-- ────────────────────────────────────────────────────

ALTER TABLE error_logs ADD COLUMN github_issue_url TEXT;
